"""Adversarial invariants for the pullback episode owner (synthetic only).

Every path here is generated by stdlib ``random`` with fixed seeds — no
recorded market data, no vendor names, no forecast, probability or quantile is
asserted anywhere. The suite states structural laws the single episode owner
must satisfy on every available observation:

I1  drawdown_pct is non-positive and equals its own definition;
I2  the episode low never sits above the current close or the retained peak;
I3  loss_recovered_pct is a clamped percentage or None;
I4  active is True exactly for the three live phases;
I5  the drawn price path is a clean, capped, non-positive series ending as-of;
I6  a recent-peak episode marks both peak and low on the drawn path;
I7  no_new_low_closes is a bounded non-negative count;
I8  tied lows resolve to the FIRST occurrence;
I9  one shock close at Rules.shock_drawdown confirms underway at once;
I10 garbage rows fail closed into a well-formed observation, never a raise;
I11 the replay is deterministic and input-order insensitive.
"""
from __future__ import annotations

import functools
import json
import random
from collections import Counter
from datetime import date, timedelta

import pytest

from lib.pullback_observation import PATH_MAX_CLOSES, RULES, SCHEMA, observe

START = date(2024, 3, 4)  # a Monday; rows walk forward over weekdays only
LEAD = 70  # flat lead closes before the generators shape the path
ACTIVE_PHASES = ("underway", "stabilizing", "recovering")
PHASES = {"monitoring", "developing", "underway", "stabilizing", "recovering", "repaired"}


def is_session(day):
    return day.weekday() < 5


def rows_for(closes):
    """Consecutive weekday rows from START — the synthetic calendar fixture."""
    day = START
    rows = []
    for value in closes:
        while not is_session(day):
            day += timedelta(days=1)
        rows.append((day.isoformat(), float(value)))
        day += timedelta(days=1)
    return rows


def expected_of(rows):
    return date.fromisoformat(rows[-1][0])


def run(rows, expected=None):
    return observe(rows, expected_session=expected or expected_of(rows), is_session=is_session)


# ── synthetic path families (fixed seeds, stdlib random only) ────────────────


def _walk(rng):
    drift = rng.choice([-0.003, -0.0015, 0.0, 0.0008, 0.0015])
    sigma = rng.choice([0.008, 0.015, 0.025])
    price = rng.uniform(40.0, 240.0)
    closes = []
    for _ in range(rng.randrange(70, 200)):
        closes.append(price)
        price = max(1.0, price * (1.0 + drift + rng.gauss(0.0, sigma)))
    return closes


def _crash_recover(rng):
    base = rng.uniform(90.0, 110.0)
    drop = rng.uniform(0.06, 0.22)
    crash_len = rng.randrange(2, 8)
    rec_len = rng.randrange(15, 70)
    target = rng.uniform(0.0, 1.15)  # fraction of the loss retraced, may overshoot
    crash = [base * (1.0 - drop * (step + 1) / crash_len) for step in range(crash_len)]
    return [base] * LEAD + crash + [
        crash[-1] + (base - crash[-1]) * target * (step + 1) / rec_len
        for step in range(rec_len)
    ]


def _slow_bleed(rng):
    rate = rng.uniform(0.0008, 0.004)
    start = rng.uniform(80.0, 130.0)
    return [start * (1.0 - rate) ** step for step in range(rng.randrange(70, 200))]


def _v_shape(rng):
    depth = rng.uniform(0.10, 0.30)
    down_len = rng.randrange(8, 30)
    up_len = rng.randrange(20, 70)
    bottom = 100.0 * (1.0 - depth)
    target = rng.uniform(0.3, 1.3)
    down = [100.0 * (1.0 - depth * (step + 1) / down_len) for step in range(down_len)]
    up = [bottom + (100.0 * target - bottom) * (step + 1) / up_len for step in range(up_len)]
    return [100.0] * LEAD + down + up


def _flat(rng):
    return [rng.choice([0.5, 5.0, 37.25, 100.0, 1234.5])] * rng.randrange(70, 200)


def _tied_low_plateau(rng):
    """A decline into a repeated floor value, optionally rebounded and re-tested."""
    depth = rng.uniform(0.05, 0.25)
    down_len = rng.randrange(5, 20)
    down = [100.0 * (1.0 - depth * (step + 1) / down_len) for step in range(down_len)]
    floor = down[-1]
    body = [100.0] * LEAD + down + [floor] * rng.randrange(2, 9)
    if rng.random() < 0.6:
        rebound_len = rng.randrange(2, 12)
        bounce = rng.uniform(0.2, 0.6)
        body += [floor + (100.0 - floor) * bounce * (step + 1) / rebound_len
                 for step in range(rebound_len)]
        body += [floor] * rng.randrange(2, 6)
        exit_len = rng.randrange(5, 40)
        body += [floor + (100.0 - floor) * bounce * (step + 1) / exit_len
                 for step in range(exit_len)]
    return body


def _monotone_ties(rng):
    """Non-increasing after the lead: the episode low must be the FIRST minimum."""
    price = 100.0
    tail = []
    for _ in range(rng.randrange(12, 70)):
        price *= 1.0 - rng.choice([0.0, 0.0, 0.001, 0.004, 0.01, 0.02])
        tail.append(price)
    return [100.0] * rng.randrange(65, 80) + tail


def _long_paths(rng):
    out = []
    for _ in range(4):  # long bleed: the drawn path cap must engage
        out.append([100.0] * LEAD
                   + [100.0 * (1.0 - 0.0018 * (step + 1)) for step in range(rng.randrange(230, 260))])
    for _ in range(4):  # early crash then a long flat floor: the peak ages past the cap
        low = 100.0 * (1.0 - rng.uniform(0.08, 0.2))
        out.append([100.0] * 10 + [low] * rng.randrange(280, 320))
    return out


def _with_gaps(rows, rng):
    """Drop interior rows — the owning calendar still calls those weekdays sessions."""
    gone = set(rng.sample(range(len(rows) - 1), rng.randrange(1, 9)))
    return [row for pos, row in enumerate(rows) if pos not in gone]


@functools.lru_cache(maxsize=1)
def _pool():
    """(rows, observation, tags) for every synthetic path, built once."""
    rng = random.Random(20261011)
    entries = []

    def add(closes, tags, rows=None):
        rows = rows if rows is not None else rows_for(closes)
        entries.append((rows, run(rows), frozenset(tags)))

    for _ in range(52):
        add(_walk(rng), ["walk"])
    for _ in range(44):
        add(_crash_recover(rng), ["crash"])
    for _ in range(40):
        add(_slow_bleed(rng), ["bleed"])
    for _ in range(40):
        add(_v_shape(rng), ["vshape"])
    for _ in range(32):
        add(_flat(rng), ["flat"])
    for _ in range(24):
        add(_tied_low_plateau(rng), ["tied"])
    for _ in range(24):
        add(_monotone_ties(rng), ["tied", "monotone"])
    for closes in _long_paths(rng):
        add(closes, ["long"])
    for _ in range(48):
        maker = rng.choice([_walk, _crash_recover, _v_shape, _slow_bleed])
        add(None, ["gaps"], rows=_with_gaps(rows_for(maker(rng)), rng))
    return tuple(entries)


# ── shared assertions ────────────────────────────────────────────────────────


def _assert_well_formed(obs):
    """Every packet invariant that must hold on ANY available observation."""
    assert obs["schema"] == SCHEMA
    assert obs["phase"] in PHASES
    assert (obs["active"] is True) == (obs["phase"] in ACTIVE_PHASES)
    assert obs["drawdown_pct"] == round(min(0, 100.0 * (obs["close"] / obs["peak_close"] - 1.0)), 4)
    if obs["low_close"] is not None:
        assert obs["low_close"] <= obs["close"]
        assert obs["low_close"] <= obs["peak_close"]
        recovered = obs["loss_recovered_pct"]
        assert recovered is None or 0.0 <= recovered <= 100.0
    path = obs["price_path"]
    assert len(path["dates"]) == len(path["vals"])
    assert 0 < len(path["dates"]) <= PATH_MAX_CLOSES
    assert all(a < b for a, b in zip(path["dates"], path["dates"][1:]))
    assert all(v <= 0 for v in path["vals"])


def _record_distance(rows, session_iso):
    """Records strictly after ``session_iso`` — exact index distance to as-of."""
    return len(rows) - 1 - [d for d, _ in rows].index(session_iso)


def _assert_unavailable(obs):
    assert isinstance(obs["quality"], str) and obs["quality"]
    assert obs["phase"] == "unavailable" and obs["active"] is None
    assert obs["drawdown_pct"] is None and obs["loss_recovered_pct"] is None


# ── fixture sanity ───────────────────────────────────────────────────────────


def test_pool_is_large_available_and_family_diverse():
    pool = _pool()
    assert len(pool) >= 300
    counts = Counter()
    for rows, obs, tags in pool:
        assert obs["available"] is True
        assert all(a < b for (a, _), (b, _) in zip(rows, rows[1:]))
        assert all(p > 0 for _, p in rows)
        assert is_session(expected_of(rows))
        counts.update(tags)
    assert counts["walk"] >= 45
    assert counts["crash"] >= 40
    assert counts["bleed"] >= 35
    assert counts["vshape"] >= 35
    assert counts["flat"] >= 30
    assert counts["tied"] >= 40
    assert counts["monotone"] >= 20
    assert counts["gaps"] >= 40
    assert counts["long"] >= 8


# ── I1 … I7 on every available observation ───────────────────────────────────


def test_i1_drawdown_is_nonpositive_and_matches_its_definition():
    for _rows, obs, _tags in _pool():
        assert obs["drawdown_pct"] == round(
            min(0, 100.0 * (obs["close"] / obs["peak_close"] - 1.0)), 4)
        assert obs["drawdown_pct"] <= 0


def test_i2_episode_low_bounds_close_and_peak():
    for _rows, obs, _tags in _pool():
        if obs["low_close"] is None:
            continue
        assert obs["low_close"] <= obs["close"]
        assert obs["low_close"] <= obs["peak_close"]
        worst = 1.0 - obs["low_close"] / obs["peak_close"]
        current = 1.0 - obs["close"] / obs["peak_close"]
        assert worst >= current - 1e-9


def test_i3_loss_recovered_is_a_clamped_percentage_or_none():
    for _rows, obs, _tags in _pool():
        recovered = obs["loss_recovered_pct"]
        assert recovered is None or 0.0 <= recovered <= 100.0


def test_i4_active_is_true_exactly_for_the_live_phases():
    for _rows, obs, _tags in _pool():
        assert (obs["active"] is True) == (obs["phase"] in ACTIVE_PHASES)


def test_i5_price_path_is_a_clean_capped_nonpositive_series_ending_asof():
    for _rows, obs, _tags in _pool():
        path = obs["price_path"]
        dates, vals = path["dates"], path["vals"]
        assert len(dates) == len(vals)
        assert 0 < len(dates) <= PATH_MAX_CLOSES
        assert all(a < b for a, b in zip(dates, dates[1:]))
        assert dates[-1] == obs["asof"] == obs["expected_session"]
        assert all(v <= 0 for v in vals)


def test_i6_recent_peak_episode_marks_peak_and_low_on_the_drawn_path():
    for rows, obs, _tags in _pool():
        if obs["low_session"] is None:
            continue
        if _record_distance(rows, obs["peak_session"]) >= PATH_MAX_CLOSES:
            continue
        drawn = set(obs["price_path"]["dates"])
        assert obs["peak_session"] in drawn
        assert obs["low_session"] in drawn


def test_i7_no_new_low_count_is_bounded_by_the_observed_episode():
    for _rows, obs, _tags in _pool():
        count = obs["no_new_low_closes"]
        if count is None:
            continue
        assert isinstance(count, int) and not isinstance(count, bool)
        assert 0 <= count <= obs["observed_closes_since_onset"]


# ── I8 tied lows ─────────────────────────────────────────────────────────────


def test_i8_tied_lows_resolve_to_the_first_occurrence():
    rows = rows_for([100.0] * LEAD + [97.0, 96.0, 96.0, 96.5, 97.5])
    obs = run(rows)
    assert obs["low_session"] == rows[LEAD + 1][0]  # the first 96.0, not its tie
    assert obs["low_session"] != rows[LEAD + 2][0]
    assert obs["phase"] in ACTIVE_PHASES

    for path_rows, obs, tags in _pool():
        if obs["low_session"] is None:
            continue
        closes = [p for _, p in path_rows]
        low_pos = [d for d, _ in path_rows].index(obs["low_session"])
        # The episode low stays the running minimum to the end: no later close
        # is strictly below it (a tie never displaces the first occurrence).
        assert all(p >= closes[low_pos] for p in closes[low_pos + 1:])
        if "monotone" not in tags:
            continue
        peak_pos = [d for d, _ in path_rows].index(obs["peak_session"])
        after = range(peak_pos + 1, len(closes))
        floor = min(closes[j] for j in after)
        first = next(j for j in after if closes[j] == floor)
        assert obs["low_session"] == path_rows[first][0]


# ── I9 shock confirmation ────────────────────────────────────────────────────


@pytest.mark.parametrize("factor", [1.0, 1.35, 2.0])
def test_i9_single_shock_close_confirms_underway_at_once(factor):
    rows = rows_for([100.0] * LEAD + [100.0 - 100.0 * RULES.shock_drawdown * factor])
    obs = run(rows)
    assert obs["active"] is True and obs["phase"] == "underway"
    assert obs["observed_closes_since_onset"] == 1
    assert obs["onset_session"] == rows[-1][0]


def test_i9_single_close_between_onset_and_shock_stays_developing():
    depth = (RULES.onset_drawdown + RULES.shock_drawdown) / 2.0
    rows = rows_for([100.0] * LEAD + [100.0 - 100.0 * depth])
    obs = run(rows)
    assert obs["active"] is False and obs["phase"] == "developing"
    assert obs["onset_session"] is None


# ── I10 garbage rows fail closed ─────────────────────────────────────────────


def _splice(rows, value):
    pos = len(rows) // 2
    return rows[:pos] + [(rows[pos][0], value)] + rows[pos + 1:]


def _future_row(rows, value):
    day = expected_of(rows) + timedelta(days=1)
    while not is_session(day):
        day += timedelta(days=1)
    return (day.isoformat(), value)


def _inject_garbage(rows, name):
    """(rows2, expected_session) for one garbage variant."""
    expected = expected_of(rows)
    if name == "identical_duplicate":
        return rows + [rows[-1]], expected
    if name == "conflicting_duplicate":
        return rows + [(rows[-1][0], rows[-1][1] * 0.5)], expected
    if name == "shuffled_order":
        shuffled = rows[:]
        random.Random(77).shuffle(shuffled)
        return shuffled, expected
    if name == "bad_stamp":
        return rows + [("2025-99-99", 100.0)], expected
    if name == "non_string_stamp":
        return rows + [(date(2025, 3, 29), 100.0)], expected
    if name == "non_iterable_row":
        return rows + [123.0], expected
    if name == "future_nan_row":
        return rows + [_future_row(rows, float("nan"))], expected
    values = {
        "nan_close": float("nan"),
        "inf_close": float("inf"),
        "zero_close": 0.0,
        "negative_close": -3.5,
        "none_close": None,
        "bool_close": True,
        "string_close": "100.0",
    }
    return _splice(rows, values[name]), expected


AVAILABLE_AFTER = {
    "identical_duplicate": True,   # collapses, still a current view
    "shuffled_order": True,        # the replay sorts
    "future_nan_row": True,        # excluded before price validation
}


@pytest.mark.parametrize("name", sorted(AVAILABLE_AFTER) + [
    "nan_close", "inf_close", "zero_close", "negative_close", "none_close",
    "bool_close", "string_close", "conflicting_duplicate", "bad_stamp",
    "non_string_stamp", "non_iterable_row",
])
def test_i10_garbage_rows_never_raise_and_fail_closed(name):
    for rows, _obs, _tags in _pool()[::9]:
        garbage, expected = _inject_garbage(rows, name)
        try:
            obs = run(garbage, expected=expected)
        except Exception as exc:  # a raise here IS the defect
            raise AssertionError(f"{name} raised {exc!r} on a {len(rows)}-row path") from exc
        if AVAILABLE_AFTER.get(name):
            assert obs["available"] is True
            _assert_well_formed(obs)
        else:
            assert obs["available"] is False
            _assert_unavailable(obs)
        json.dumps(obs, allow_nan=False)


# ── I11 determinism ──────────────────────────────────────────────────────────


def test_i11_same_input_twice_and_shuffled_input_agree_exactly():
    for rows, obs, _tags in _pool():
        expected = expected_of(rows)
        first = observe(rows, expected_session=expected, is_session=is_session)
        second = observe(rows, expected_session=expected, is_session=is_session)
        assert first == second == obs
        shuffled = rows[:]
        random.Random(20260929).shuffle(shuffled)
        assert observe(shuffled, expected_session=expected, is_session=is_session) == obs
