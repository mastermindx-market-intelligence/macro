def test_source_correction_changed_generation_invalidates_old_ranks():
    observation, cal = originals()
    later = copy.deepcopy(observation)
    later["snapshot_sha256"] = "e"*64
    later["source_generation_sha256"] = "f"*64
    later["supersedes_generation_sha256"] = observation["source_generation_sha256"]
    result = build_private_tp2_view(
        observation=later, calibration=cal, view_asof_ns=cal["evaluation_ns"]+1)
    assert result["state"] == "CALIBRATION_STALE_SOURCE_GENERATION"
    assert result["source_generation_sha256"] == "f"*64
    assert result["historical_ruler"] is None
    assert result["intraday_minute_baseline"] is None


