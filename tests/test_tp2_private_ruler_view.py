def originals():
    raw = FIXTURE.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == (
        "a499fb167aab3498943663598593408b008b2e98c79565e07177c310cba4a196")
    item = json.loads(raw)
    assert item["schema"] == "tp2.synthetic_tpb_private_input/v0"
    assert item["source_published_head"] == SOURCE_REV
    assert item["note"] == "SYNTHETIC_SOURCE_NO_VENDOR_AUTHENTICITY_OR_FINALITY"
    return item["observation"], item["calibration"]


def context(*, observation=None, calibration=None, now=None):
    original, golden = originals()
    return build_private_tp2_view(
        observation=original if observation is None else observation,
        calibration=golden if calibration is None else calibration,
        view_asof_ns=golden["evaluation_ns"]+1 if now is None else now,
    )


