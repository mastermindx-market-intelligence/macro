"""TP-2 data-only private view contract over ACTUAL TP-B Python synthetic golden.

The golden fixture is generated by TP-B's existing source and calibration
functions at the pinned review commit, not by an invented standalone emitter.
No real vendor data, credentials, auth route, browser or public delivery.
"""
import copy
import hashlib
import json
from pathlib import Path

import pytest

from engine.tp2_private_ruler_view import (
    SCHEMA, TP2PrivateViewRefusal, build_private_tp2_view,
)

FIXTURE = Path(__file__).parent / "fixtures/tp2_tpb_source.synthetic.v0.json"
SOURCE_REV = "23787b0518b6bd9ab807194698014b32976d1f48"


def originals():
    raw = FIXTURE.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == (
        "a499fb167aab3498943663598593408b008b2e98c79565e07177c310cba4a196")
    item = json.loads(raw)
    assert item["schema"] == "tp2.synthetic_tpb_private_input/v0"
    assert item["source_published_head"] == SOURCE_REV
    assert item["note"] == "SYNTHETIC_SOURCE_NO_VENDOR_AUTHENTICITY_OR_FINALITY"
    return item["observation"], item["calibration"]


def context(*, observation=None, calibration=None, now=None):
    original, golden = originals()
    return build_private_tp2_view(
        observation=original if observation is None else observation,
        calibration=golden if calibration is None else calibration,
        view_asof_ns=golden["evaluation_ns"]+1 if now is None else now,
    )


def test_golden_private_tp2_separates_print_cluster_day_from_ats_and_liveness():
    result = context()
    assert result["schema"] == SCHEMA
    assert result["state"] == "PRIVATE_TPB_RESEARCH_CONTEXT_ONLY"
    assert result["ticker"] == "SPY"
    assert result["session"] == "2026-10-08:RTH"
    obs = result["observed_source"]
    assert obs["largest_individual_print_usd"] == "200000"
    assert obs["largest_same_level_cluster_usd"] == "300000"
    assert obs["measured_rth_trf_notional_usd"] == "500000"
    assert obs["n_trf_observed"] == 3
    assert result["historical_ruler"]["SINGLE_PRINT"]["rank_desc_in_observed_sample"] == 1
    assert result["historical_ruler"]["SAME_LEVEL_CLUSTER"]["rank_desc_in_observed_sample"] is None
    assert result["historical_ruler"]["DAILY_TOTAL"]["rank_desc_in_observed_sample"] == 1
    assert result["intraday_minute_baseline"]["conditioning"] == (
        "EXACT_MINUTE_INDEX_RTH_CUMULATIVE_ONLY")
    assert result["intraday_minute_baseline"]["cumulative_offexchange_share"] == "0.4"
    assert result["intraday_minute_baseline"]["median"] == "0.22"
    assert result["live_block_tape"] is None
    assert result["repeat_print_price_shelves"] is None
    assert result["live_signed_offexchange_flow"] is None
    assert result["named_ats_attribution"] is None
    assert result["finra_ats_delayed_context"] is None
    assert result["eod_weekly_context"] == "UNCHANGED_SEPARATE_EXISTING_CONSUMER"
    assert result["public_delivery_allowed"] is False
    assert result["source_authenticated"] is False
    assert result["ranking_trading_alert_authority"] is False
    assert result["signal"] is None


def test_lossless_private_clock_uses_unsigned_decimal_text_not_json_number():
    result = context()
    assert type(result["observation_asof_ns_decimal"]) is str
    assert int(result["observation_asof_ns_decimal"]) > 2**53
    assert result["view_asof_ns_decimal"].isdigit()
    encoded = json.dumps(result, sort_keys=True, separators=(",", ":"))
    assert '"view_asof_ns_decimal":"' in encoded
    assert '"observation_asof_ns_decimal":"' in encoded
    assert str(int(result["view_asof_ns_decimal"])) in encoded


def test_explicit_no_source_and_no_new_auth_plane():
    result = build_private_tp2_view(observation=None, view_asof_ns=100)
    assert result["state"] == "NO_TPB_OBSERVATION_SOURCE"
    assert result["observed_source"] is None
    assert result["historical_ruler"] is None
    assert result["live_block_tape"] is None
    assert result["public_delivery_allowed"] is False
    assert result["eod_weekly_context"] == "UNCHANGED_SEPARATE_EXISTING_CONSUMER"
    _, golden = originals()
    with pytest.raises(TP2PrivateViewRefusal, match="without an original source"):
        build_private_tp2_view(observation=None, calibration=golden, view_asof_ns=100)


