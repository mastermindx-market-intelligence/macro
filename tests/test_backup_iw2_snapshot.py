@pytest.mark.parametrize('mutation', ['missing', 'extra', 'duplicate', 'foreign-prefix', 'content', 'manifest'])
def test_archive_rejects_wrong_members_or_content(mutation):
    raw = (Path(__file__).parent / 'fixtures/user_table_backup_v1.tar.gz').read_bytes()
    with tarfile.open(fileobj=io.BytesIO(raw), mode='r:gz') as archive:
        members = [(m.name, archive.extractfile(m).read()) for m in archive.getmembers()]
    if mutation == 'missing': members.pop()
    elif mutation == 'extra': members.append(('extra/tables/evil.jsonl', b'{}\n'))
    elif mutation == 'duplicate': members.append(members[-1])
    elif mutation == 'foreign-prefix': members = [('foreign/' + n.split('/', 1)[1], d) for n, d in members]
    elif mutation == 'content': members[-1] = (members[-1][0], b'{"changed":true}\n')
    else: members[0] = (members[0][0], b'not json')
    out = io.BytesIO()
    with tarfile.open(fileobj=out, mode='w:gz') as archive:
        for name, data in members: bak._add_bytes(archive, name, data)
    with pytest.raises(bak.BackupError): bak.parse_tar(out.getvalue())


