def test_real_postgres_snapshot_restore_and_atomic_failure(postgres):
    url, sql = postgres
    payload = {'layout_revision_id': 'kept-exact', 'revision': 2,
               'value': Decimal('1.123456789012345678901'), 'quoted': "'\\$mmx_restore$"}
    encoded = bak.json_value(payload).replace("'", "''")
    sql('\n'.join(f"INSERT INTO {n} VALUES ('{n}', '{encoded}');" for n in bak.IW2_TABLES))
    tables, _ = bak.parse_snapshot(sql(bak.snapshot_query(REF)).encode(), REF)
    assert all(t.rows[0]['payload'] == payload for t in tables.values())
    sql('TRUNCATE ' + ','.join(bak.IW2_TABLES) + ';')
    assert bak.pg_insert_jsonl(url, tables) == {n: 1 for n in bak.IW2_TABLES}
    again, _ = bak.parse_snapshot(sql(bak.snapshot_query(REF)).encode(), REF)
    assert {n: t.rows for n, t in again.items()} == {n: t.rows for n, t in tables.items()}
    sql('TRUNCATE ' + ','.join(bak.IW2_TABLES) + ';')
    sql("ALTER TABLE investigation_mutation_receipts ADD CONSTRAINT reject_receipt CHECK (id <> 'investigation_mutation_receipts');")
    with pytest.raises(bak.BackupError, match='rolled back'): bak.pg_insert_jsonl(url, tables)
    assert all(not t.rows for t in bak.parse_snapshot(sql(bak.snapshot_query(REF)).encode(), REF)[0].values())
    sql('ALTER TABLE investigation_mutation_receipts DROP CONSTRAINT reject_receipt;')
    changed = copy.deepcopy(tables)
    changed['profiles'].rows[0]['unexpected_column'] = 'cannot round trip'
    with pytest.raises(bak.BackupError, match='rolled back'): bak.pg_insert_jsonl(url, changed)
    assert sql('SELECT count(*) FROM profiles;').strip() == '0'


def test_legacy_rest_restore_preserves_decimal_type(monkeypatch):
    sent = []
    class Response:
        def __enter__(self): return self
        def __exit__(self, *args): pass
        def read(self): return b''
    def transport(request, **kwargs):
        sent.append(request.data)
        return Response()
    monkeypatch.setattr(bak.urllib.request, 'urlopen', transport)
    rows = [{'value': Decimal('1.123456789012345678901')}]
    assert bak.write_via_rest('chart_layouts', rows, base_url='https://scratch.invalid', service_key='synthetic') == 1
    assert json.loads(sent[0], parse_float=Decimal) == rows
    assert b'"1.123456789012345678901"' not in sent[0]


def test_typed_iw2_links_and_source_timezone_survive(postgres):
    url, sql = postgres
    actor = '11111111-1111-4111-8111-111111111111'
    target = '22222222-2222-4222-8222-222222222222'
    retained = '33333333-3333-4333-8333-333333333333'
    layout = '44444444-4444-4444-8444-444444444444'
    op = '55555555-5555-4555-8555-555555555555'
    sql('''DROP TABLE investigations, investigation_revisions, investigation_mutation_receipts, chart_layout_revisions;
    CREATE TABLE investigations(id uuid PRIMARY KEY, user_id uuid NOT NULL, current_revision integer NOT NULL, lifecycle text NOT NULL, created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, UNIQUE(id,user_id));
    CREATE TABLE investigation_revisions(investigation_id uuid, user_id uuid, revision integer, action text, lifecycle text, manifest jsonb, committed_at timestamptz, PRIMARY KEY(investigation_id,revision), FOREIGN KEY(investigation_id,user_id) REFERENCES investigations(id,user_id));
    CREATE TABLE investigation_mutation_receipts(user_id uuid, operation_id uuid, request jsonb, result jsonb, PRIMARY KEY(user_id,operation_id));
    CREATE TABLE chart_layout_revisions(id uuid PRIMARY KEY, user_id uuid, layout_id uuid, source_revision integer, name text, config jsonb, digest text, retained_at timestamptz);''')
    manifest = {'layout_refs': [{'layout_id': layout, 'layout_revision_id': retained, 'digest': 'a'*64}], 'evidence_refs': [{'state': 'HISTORICAL_UNAVAILABLE'}]}
    m = json.dumps(manifest).replace("'", "''")
    sql(f"""BEGIN;
    INSERT INTO investigations VALUES ('{target}','{actor}',2,'removed','2026-10-09T01:00Z','2026-10-09T02:00Z');
    INSERT INTO chart_layout_revisions VALUES ('{retained}','{actor}','{layout}',5,'retained','{{}}','{'a'*64}','2026-10-09T01:00Z');
    INSERT INTO investigation_revisions VALUES ('{target}','{actor}',1,'create','active','{m}','2026-10-09T01:00Z'),('{target}','{actor}',2,'remove','removed','{m}','2026-10-09T02:00Z');
    INSERT INTO investigation_mutation_receipts VALUES ('{actor}','{op}','{{"target":"{target}"}}','{{"id":"{target}","revision":2,"manifest":{m}}}'); COMMIT;""")
    raw = sql("SET TIME ZONE 'America/Vancouver';\n" + bak.snapshot_query(REF)).encode()
    tables, source = bak.parse_snapshot(raw, REF)
    sql('TRUNCATE ' + ','.join(bak.IW2_TABLES) + ';')
    bak.pg_insert_jsonl(url, tables, timezone=source['timezone'])
    restored, _ = bak.parse_snapshot(sql("SET TIME ZONE 'America/Vancouver';\n" + bak.snapshot_query(REF)).encode(), REF)
    assert {n: t.rows for n, t in restored.items()} == {n: t.rows for n, t in tables.items()}
    assert sql('SELECT count(*) FROM investigations h JOIN investigation_revisions r ON r.investigation_id=h.id AND r.user_id=h.user_id AND r.revision=h.current_revision;').strip() == '1'
    assert restored['investigation_revisions'].rows[0]['manifest'] == manifest
