import { build } from "esbuild";
import { readFile, writeFile, copyFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const source = JSON.parse(await readFile(path.join(here, "terminal-sources.json"), "utf8"));
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
for (const [name, receipt] of Object.entries(source.sources)) {
  if (hash(await readFile(path.join(here, "vendor/terminal", name))) !== receipt.sha256)
    throw new Error("Canonical Terminal source digest mismatch: " + name);
}
const statementOutput = await build({
  absWorkingDir: here, entryPoints: ["statements.ts"], bundle: true, write: false,
  format: "iife", globalName: "MMBrainFinanceMath", platform: "browser",
  target: ["es2020"], minify: true, treeShaking: true, legalComments: "inline",
  metafile: true,
  plugins: [{
    name: "exclude-unused-terminal-network-owner",
    setup(b) {
      b.onResolve({ filter: /^\.\/dataCache$/ }, () => ({ path: "dataCache", namespace: "excluded-reader" }));
      b.onLoad({ filter: /.*/, namespace: "excluded-reader" }, () => ({
        contents: "export function getJSON(){throw new Error('Reader excluded from pure bundle')} export function getOhlc(){throw new Error('Reader excluded from pure bundle')}",
        loader: "js",
      }));
    },
  }],
});
const statements = statementOutput.outputFiles[0].text;
if (/fetch\(|indexedDB|localStorage|sessionStorage|Reader excluded|https?:\/\//.test(statements))
  throw new Error("Statement bundle retained an I/O owner");
const mathOutput = await build({
  absWorkingDir: here, entryPoints: ["math.ts"], bundle: true, write: false,
  format: "iife", globalName: "MMBrainMath", platform: "browser",
  target: ["es2020"], minify: true, treeShaking: true, legalComments: "inline",
});
// KaTeX's unused error-markup fallback must inherit host ink, not introduce a
// vendor palette. Strict rendering still throws and preserves plain formula text.
const mathRaw = mathOutput.outputFiles[0].text;
if ((mathRaw.match(/#cc0000/g) || []).length !== 1) throw new Error("KaTeX default error-color contract changed");
const math = mathRaw.replace('default:"#cc0000"', 'default:"currentColor"');
if (math.includes("#cc0000")) throw new Error("KaTeX error-color adaptation did not apply");
// Standalone chat uses the exact shared widget Markdown owner, not another parser.
const widget = await readFile(path.join(root, "templates/mm_brain.js"), "utf8");
const mdStart = widget.indexOf("  var MD_INLINE =");
const mdEnd = widget.indexOf("  /* ── MdStream:");
if (mdStart < 0 || mdEnd <= mdStart) throw new Error("Shared Markdown source boundaries changed");
const markdownSource = widget.slice(mdStart, mdEnd);
const markdownOutput = await build({
  stdin: {contents: "(function(){'use strict';var DOC=document;" +
    "function el(tag,cls){var e=DOC.createElement(tag);if(cls)e.className=cls;return e;}" +
    "function L(en,zh){return /^zh/i.test(DOC.documentElement.getAttribute('data-lang')||DOC.documentElement.lang||'')?zh:en;}" +
    "function requestMath(host){setTimeout(function(){if(window.MMBrainPresentation)window.MMBrainPresentation.renderMath(host);},0);}" +
    markdownSource + "window.MMBrainMarkdown={renderInto:renderMdInto,render:renderMd};})();", loader: "js"},
  write: false, minify: true, target: ["es2020"],
});
const outputs = {
  "mm_brain_markdown.js": markdownOutput.outputFiles[0].text,
  "mm_brain_finance_math_v1.js": statements,
  "mm_brain_math.js": math,
};
const manifest = { normalizer_version: source.normalizer_version, terminal_revision: source.revision,
  markdown_owner: "templates/mm_brain.js", markdown_source_sha256: hash(markdownSource),
  build_dependencies: JSON.parse(await readFile(path.join(here, "package.json"), "utf8")).devDependencies, assets: {} };
for (const [name, code] of Object.entries(outputs)) {
  const body = "// Generated by tools/brain-output/build.mjs; do not edit.\n" + code + "\n";
  for (const target of ["templates", "site"]) await writeFile(path.join(root, target, name), body);
  manifest.assets[name] = { sha256: hash(body), bytes: Buffer.byteLength(body) };
}
const registry = {visualJS:"mm_brain_visuals.js",visualCSS:"mm_brain_visuals.css",
  financeJS:"mm_brain_finance.js",financeCSS:"mm_brain_finance.css",math:"mm_brain_math.js"};
const presentationPath = path.join(root,"templates/mm_brain_presentation.js");
let presentation = await readFile(presentationPath,"utf8");
for (const [key,name] of Object.entries(registry)) {
  const digest = hash(await readFile(path.join(root,"templates",name))).slice(0,8);
  const pattern = new RegExp("("+key+":')[a-f0-9]+'");
  if(!pattern.test(presentation)) throw new Error("Presentation registry key missing: "+key);
  presentation = presentation.replace(pattern,"$1"+digest+"'");
}
await writeFile(presentationPath,presentation);
// Keep the primary cross-product widget's lazy entry points content-addressed.
let primary = widget;
for (const [key,name] of Object.entries({
  visualScriptVersion:"mm_brain_visuals.js",visualStyleVersion:"mm_brain_visuals.css",
  presentationVersion:"mm_brain_presentation.js"
})) {
  const digest = hash(await readFile(path.join(root,"templates",name))).slice(0,8);
  const pattern = new RegExp("(var "+key+" = ')[a-f0-9]+'");
  if(!pattern.test(primary)) throw new Error("Primary presentation key missing: "+key);
  primary = primary.replace(pattern,"$1"+digest+"'");
}
await writeFile(path.join(root,"templates/mm_brain.js"),primary);
await writeFile(path.join(root,"site/mm_brain.js"),primary);
const chatPath=path.join(root,"templates/chat.html");
let chat=await readFile(chatPath,"utf8");
for(const name of ["mm_brain_presentation.js","mm_brain_markdown.js","chat.css"]){
  const digest=hash(await readFile(path.join(root,"templates",name))).slice(0,8);
  chat=chat.replace(new RegExp(name.replaceAll(".","\\.")+"\\?v=[a-f0-9]+","g"),name+"?v="+digest);
}
await writeFile(chatPath,chat);
for(const name of ["mm_brain_presentation.js","mm_brain_finance.js","mm_brain_finance.css","mm_brain_visuals.css","chat.html","chat.css"])
  await copyFile(path.join(root,"templates",name),path.join(root,"site",name));
await copyFile(path.join(here, "node_modules/katex/LICENSE"), path.join(here, "KATEX-LICENSE"));
await writeFile(path.join(here, "build-manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(JSON.stringify(manifest, null, 2));
